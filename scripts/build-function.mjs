import { readFile, writeFile } from 'node:fs/promises';
import { isBuiltin } from 'node:module';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('../', import.meta.url));
const result = await build({
  absWorkingDir: root,
  entryPoints: ['server/function.ts'],
  outfile: 'cloud-function/index.js',
  banner: { js: '// Generated by npm run build:function. Edit the TypeScript sources in server/.' },
  bundle: true,
  platform: 'node',
  target: 'node24',
  format: 'cjs',
  packages: 'external',
  metafile: true
});
const lock = JSON.parse(await readFile(new URL('../package-lock.json', import.meta.url), 'utf8'));
const imports = Object.values(result.metafile.outputs).flatMap(output => output.imports);
const packages = new Set(imports.filter(entry => entry.external && !isBuiltin(entry.path)).map(({path}) => {
  const parts = path.split('/');
  return parts.slice(0, path.startsWith('@') ? 2 : 1).join('/');
}));
const dependencies = Object.fromEntries([...packages].sort().map(name => {
  const version = lock.packages['node_modules/' + name]?.version;
  if (!version || !lock.packages[''].dependencies?.[name]) throw new Error('Missing runtime dependency: ' + name);
  return [name, version];
}));

const manifest = {
  name: 'ah-marketplace-api',
  version: '1.0.0',
  private: true,
  main: 'index.js',
  engines: { node: '24.x' },
  scripts: { start: 'functions-framework --target=ahMarketplaceApi --signature-type=http' },
  dependencies
};
await writeFile(new URL('../cloud-function/package.json', import.meta.url), JSON.stringify(manifest, null, 2) + '\n');
